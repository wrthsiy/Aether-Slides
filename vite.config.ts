import { defineConfig } from 'vite';
import type { Plugin, ResolvedConfig } from 'vite';
import react from '@vitejs/plugin-react';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

/** Emits dist/sw.js: precaches the whole build and keeps it offline-capable.
 *  Cache names start with `aether-slides-` and `activate` deletes ONLY `aether-slides-*` caches, because Aether lives on the
 *  same origin (GitHub Pages) and must keep its own. [to reconcile] written from scratch: Aether's swPlugin was not available. */
export function swPlugin(prefix = 'aether-slides-'): Plugin {
  let cfg: ResolvedConfig;
  const walk = (dir: string): string[] =>
    readdirSync(dir).flatMap((f) => { const p = join(dir, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
  return {
    name: 'aether-slides-sw',
    apply: 'build',
    configResolved(c) { cfg = c; },
    closeBundle() {
      const out = cfg.build.outDir;
      const files = walk(out).filter((f) => !/(^|[\\/])sw\.js$/.test(f)).sort();
      const h = createHash('sha1');
      for (const f of files) { h.update(relative(out, f)); h.update(readFileSync(f)); }
      const base = cfg.base.endsWith('/') ? cfg.base : cfg.base + '/';
      const urls = [base, ...files.map((f) => base + relative(out, f).split(sep).join('/'))];
      const version = h.digest('hex').slice(0, 10);
      writeFileSync(join(out, 'sw.js'), `// generated by swPlugin(): do not edit
const CACHE = ${JSON.stringify(prefix + version)};
const FONTS = ${JSON.stringify(prefix + 'fonts')};
const PREFIX = ${JSON.stringify(prefix)};
const BASE = ${JSON.stringify(base)};
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((ks) => Promise.all(ks.filter((k) => k.startsWith(PREFIX) && k !== CACHE && k !== FONTS).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // Google Fonts (the editor UI and the External export preview): stale-while-revalidate in a cache that survives updates
  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    e.respondWith(caches.open(FONTS).then((c) => c.match(req).then((hit) => {
      const net = fetch(req).then((r) => { if (r.ok || r.type === 'opaque') c.put(req, r.clone()); return r; }).catch(() => hit);
      return hit || net;
    })));
    return;
  }
  if (url.origin !== location.origin || !url.pathname.startsWith(BASE)) return;
  // navigations (incl. ?presenter): network first, fall back to the cached shell
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).catch(() => caches.match(BASE, { ignoreSearch: true }).then((r) => r || caches.match(BASE + 'index.html'))));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req)));
});
`);
    },
  };
}

export default defineConfig({
  plugins: [react(), swPlugin('aether-slides-')],
  base: '/Aether-Slides/',
});
